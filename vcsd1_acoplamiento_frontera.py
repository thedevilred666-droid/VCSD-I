import sympy as sp
r, R_isla, k_0 = sp.symbols('r R_isla k_0', real=True, positive=True)
k_r = k_0 * (1 - (r / R_isla)**2)
k_centro = k_r.subs(r, 0)
k_frontera = sp.limit(k_r, r, R_isla)
dk_dr = sp.diff(k_r, r)
gradiente_frontera = dk_dr.subs(r, R_isla)
print(f"\n{'='*75}\n   AUDITORÍA TOPOLÓGICA: ACOPLAMIENTO SUAVE DE FRONTERA (VCSD-I)\n{'='*75}")
print(f"[*] Perfil de curvatura regional k(r):")
sp.pprint(k_r)
print(f"\n{'-'*75}")
print(f"[*] Curvatura intrínseca en el centro (r = 0)     : {k_centro}")
print(f"[*] Curvatura intrínseca en la frontera (r=R_isla) : {k_frontera}")
print(f"[*] Gradiente de transición en la frontera         : {gradiente_frontera}")
print(f"{'='*75}")
assert k_frontera == 0, "ERROR: La curvatura no se apaga en la frontera exterior."
print("[VERDICTO]: La geometría segmentada es consistente. La curvatura decae\nsuavemente sin escalones discontinuos en la hipersuperficie de Israel.")
print(f"{'='*75}")
